    "    'YYYY-MM-DD' when day, month and year are known ('3 Temmuz 2026').\n"
    "    'YYYY-MM'    when only month and year are known ('Temmuz 2026', 'im Juli 2026').\n"
    "    'MM-DD'      when only day and month are known, no year ('3 Temmuz', '3. Juli').\n"
